import { readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
import { format, resolveConfig } from "prettier";

const web = resolve("apps/web");
const require = createRequire(resolve(web, "package.json"));
const postcss = createRequire(require.resolve("@tailwindcss/postcss"))(
  "postcss",
);

// Public routes retain every potentially matching selector in original order.
// The complete styles remain available inside the persistent application layout.
export async function publicStyleSources() {
  const files = new Set();
  async function routes(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.isDirectory() && !["app", "api"].includes(entry.name))
        await routes(resolve(directory, entry.name));
      else if (
        entry.isFile() &&
        /^(page|layout|error|not-found|global-error)\.tsx$/.test(entry.name)
      )
        files.add(resolve(directory, entry.name));
    }
  }
  await routes(resolve(web, "app"));
  // Follow component imports, including their lazily opened public surfaces.
  const texts = [];
  for (const file of files) {
    const source = await readFile(file, "utf8");
    texts.push(source);
    const ast = ts.createSourceFile(
      file,
      source,
      ts.ScriptTarget.Latest,
      true,
      ts.ScriptKind.TSX,
    );
    async function visit(node) {
      const specifier = ts.isImportDeclaration(node)
        ? node.moduleSpecifier
        : ts.isCallExpression(node) &&
            node.expression.kind === ts.SyntaxKind.ImportKeyword
          ? node.arguments[0]
          : undefined;
      if (specifier && ts.isStringLiteral(specifier)) {
        const name = specifier.text;
        const base = name.startsWith("@/")
          ? resolve(web, name.slice(2))
          : name.startsWith(".")
            ? resolve(dirname(file), name)
            : "";
        if (
          base.startsWith(resolve(web, "components")) &&
          !base.endsWith(".css")
        ) {
          const target = base.endsWith(".tsx") ? base : `${base}.tsx`;
          try {
            await readFile(target);
            files.add(target);
          } catch (error) {
            if (error.code !== "ENOENT") throw error;
          }
        }
      }
      for (const child of node.getChildren(ast)) await visit(child);
    }
    await visit(ast);
  }
  // Include conditional/template class fragments and CSS-module member names.
  // Extra tokens retain harmless rules; omitted tokens would risk public styles.
  return new Set(
    texts.flatMap((source) => source.match(/[a-zA-Z_][a-zA-Z0-9_-]*/g) ?? []),
  );
}

export function selectPublicStyles(source, tokens) {
  const ast = postcss.parse(source);
  ast.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name))
      return;
    const possible = rule.selectors.some((selector) => {
      // Negative/relational selectors can match without their named classes.
      // Retain them conservatively instead of pretending a token check is a DOM.
      if (/:(not|has|is|where)\(/.test(selector)) return true;
      const classes = [
        ...selector.matchAll(/\.([a-zA-Z_][a-zA-Z0-9_-]*)/g),
      ].map((match) => match[1]);
      return classes.every((name) => tokens.has(name));
    });
    if (!possible) rule.remove();
  });
  ast.walkComments((comment) => comment.remove());
  ast.walkAtRules((rule) => {
    if (rule.nodes?.length === 0) rule.remove();
  });
  return ast.toString();
}

export async function generatePublicStyles() {
  const tokens = await publicStyleSources();
  const parts = await Promise.all(
    ["workspace.css", "design-system.css"].map(async (name) =>
      selectPublicStyles(
        await readFile(resolve(web, "app", name), "utf8"),
        tokens,
      ),
    ),
  );
  return format(
    "/* Generated by scripts/public-style-budget.mjs. Keep complete application CSS intact. */\n" +
      parts.join("\n") +
      "\n",
    {
      ...(await resolveConfig(resolve(web, "app/public-product.css"))),
      parser: "css",
    },
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const generated = await generatePublicStyles();
  const target = resolve(web, "app/public-product.css");
  if (process.argv.includes("--write")) await writeFile(target, generated);
  else if ((await readFile(target, "utf8")) !== generated)
    throw new Error(
      "Public styles changed. Run node scripts/public-style-budget.mjs --write, then the public CSS parity checks.",
    );
  console.log(
    `Public product styles: ${Buffer.byteLength(generated)} raw bytes; source coverage verified.`,
  );
}
